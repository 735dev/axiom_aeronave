import {
  FieldDef,
  StatusDef,
  StepDef,
  Ticket,
  TicketType,
} from '@/features/tickets/types/ticket.types';

function field(
  key: string,
  label: string,
  type: FieldDef['type'],
  order: number,
  extra: Partial<FieldDef> = {},
): FieldDef {
  return {
    id: `f-${key}-${order}`,
    key,
    label,
    type,
    required: extra.required ?? false,
    width: extra.width ?? 'full',
    sort_order: order,
    ...extra,
  };
}

function status(
  code: string,
  name: string,
  color: StatusDef['color'],
  order: number,
  extra: Partial<StatusDef> = {},
): StatusDef {
  return {
    id: `s-${code}-${order}`,
    code,
    name,
    color,
    sort_order: order,
    is_initial: extra.is_initial ?? order === 1,
    is_final: extra.is_final ?? false,
    counts_as_committed: extra.counts_as_committed ?? true,
  };
}

function step(
  code: string,
  name: string,
  order: number,
  roleId?: string,
  roleName?: string,
  required = true,
  requiresSignature = false,
): StepDef {
  return {
    id: `st-${code}-${order}`,
    code,
    name,
    role_id: roleId,
    role_name: roleName,
    required,
    requires_signature: requiresSignature,
    sort_order: order,
  };
}

